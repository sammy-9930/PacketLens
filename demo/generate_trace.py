#!/usr/bin/env python3
"""Decode synthetic packets with cpp-sniffer and export one-second replay bins."""

import json
from pathlib import Path
import re
import struct
import subprocess

DEMO = Path(__file__).resolve().parent
PATTERN = re.compile(r" protocol=([A-Za-z0-9]+)\(\d+\) bytes=(\d+)$")


def packet(protocol, payload):
    size = (40 if protocol == 58 else 20) + len(payload)
    if protocol == 58:
        return (
            struct.pack("!IHBB", 6 << 28, size - 40, protocol, 64)
            + bytes(15) + b"\x01" + bytes(15) + b"\x02" + payload
        )
    return (
        struct.pack("!BBHHHBBH4s4s", 0x45, 0, size, 0, 0, 64, protocol, 0,
                    bytes([192, 0, 2, 1]), bytes([198, 51, 100, 2]))
        + payload
    )


def udp(destination, payload):
    return struct.pack("!HHHH", 49152, destination, len(payload) + 8, 0) + payload


def tcp(destination, payload):
    header = struct.pack("!HHIIHHHH", 49152, destination, 1, 1, 0x5018, 4096, 0, 0)
    return header + payload


def fixtures():
    http = b"GET /status HTTP/1.1\r\nHost: demo.example\r\nConnection: close\r\n\r\n"
    dns = struct.pack("!6H", 1, 0x0100, 1, 0, 0, 0) + b"\x04demo\x07example\x00\x00\x01\x00\x01"
    ntp = b"\x23" + bytes(47)  # Version 4 client request.
    return [
        ("TCP", None, packet(6, tcp(9000, bytes(1160))).hex()),
        ("UDP", None, packet(17, udp(9001, bytes(572))).hex()),
        ("ICMP", None, packet(1, b"\x08" + bytes(63)).hex()),
        ("ICMPv6", None, packet(58, b"\x80" + bytes(63)).hex()),
        ("TCP", "HTTP", packet(6, tcp(80, http)).hex()),
        ("UDP", "DNS", packet(17, udp(53, dns)).hex()),
        ("UDP", "NTP", packet(17, udp(123, ntp)).hex()),
    ]


def samples():
    for tick in range(48):
        counts = [38 + (7 * tick % 25), 12 + (3 * tick % 18), 5, 3,
                  4 + tick % 6, 3 + tick % 4, int(tick % 5 == 0)]
        if 10 <= tick < 21:
            counts[0] += 100 - 4 * abs(tick - 15)
            counts[4] += 38 - 3 * abs(tick - 15)
        if 26 <= tick < 40:
            counts[1] += 175 - 7 * abs(tick - 32)
            counts[5] += 30 - 3 * abs(tick - 32)
        yield counts


def main():
    counts = list(samples())
    traffic = fixtures()
    records = [record for interval in counts
               for (_, _, record), count in zip(traffic, interval) for _ in range(count)]
    output = subprocess.run([str(DEMO.parent / "cpp-sniffer"), "--packet-lines", "--hex-stdin"],
                            input="\n".join(records) + "\n", text=True,
                            capture_output=True, check=True).stdout
    lines = iter(output.splitlines())
    bins = []
    for interval in counts:
        protocols = {}
        applications = {}
        octets = 0
        for (expected, application, _), count in zip(traffic, interval):
            for _ in range(count):
                match = PATTERN.search(next(lines, ""))
                if not match or match[1] != expected:
                    raise ValueError(f"expected a decoded {expected} packet")
                protocols[expected] = protocols.get(expected, 0) + 1
                octets += int(match[2])
                if application:
                    applications[application] = applications.get(application, 0) + 1
        bins.append({"bytes": octets, "protocols": protocols, "applications": applications})
    if next(lines, None) is not None:
        raise ValueError("decoder returned extra packets")
    (DEMO / "trace.js").write_text(
        "// Generated by generate_trace.py from cpp-sniffer output.\n"
        + "const replayBins = " + json.dumps(bins, separators=(",", ":")) + ";\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
